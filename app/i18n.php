if (!function_exists('get_ui_language')) {
    function get_ui_language(): string {
        $raw = function_exists('get_setting') ? get_setting('ui_language', 'bilingual_ur') : 'bilingual_ur';
        if ($raw === 'bilingual' || $raw === 'bilingual_ur') return 'ur';
        if ($raw === 'bilingual_ar') return 'ar';
        if ($raw === 'bilingual_ps') return 'ps';
        if ($raw === 'bilingual_fa') return 'fa';
        if ($raw === 'english') return 'en';
        return 'ur';
    }
}

