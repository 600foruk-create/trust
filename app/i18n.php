if (!function_exists('t_phrase')) {
    function t_phrase(string $urduPhrase, ?string $lang = null): string {
        if ($lang === null) $lang = get_ui_language();
        if ($lang === 'ur' || $lang === 'en') return $urduPhrase;
        $phrases = get_multilingual_phrases();
        $clean = trim($urduPhrase);
        $cleanNoParen = trim(preg_replace('/^\((.*)\)$/u', '$1', $clean));
        if (isset($phrases[$cleanNoParen][$lang])) {
            $translated = $phrases[$cleanNoParen][$lang];
            return ($clean !== $cleanNoParen) ? '(' . $translated . ')' : $translated;
        }
        if (isset($phrases[$clean][$lang])) {
            return $phrases[$clean][$lang];
        }
        return $urduPhrase;
    }
